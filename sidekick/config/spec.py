def resolve_capture_config(cfg: dict) -> dict:
    """把 capture.mode 展开成实际的截图参数；未知模式原样返回。

    只覆盖模式表里声明的键，其余 capture.* 保留用户配置。返回副本，
    不修改调用方手里的配置。
    """
    capture = cfg.get('capture') or {}
    mode = str(capture.get('mode') or 'active').strip().lower()
    preset = CAPTURE_MODE_PRESETS.get(mode)
    if preset is None:
        return cfg
    out = copy.deepcopy(cfg)
    out['capture'].update(preset)
    return out


def default_document() -> dict:
    """默认 config.yaml 的内容和键序；不读磁盘、不带注释。

    键序按 WebUI 页面：LLM → 用户/Prompt → 角色/形象 → 游戏 → 记忆 →
    听话（STT/麦克风/打断）→ 说话（TTS/出口过滤）→ 画面与节奏
    （截屏/调度）→ 直播 → 运行内部。
    """
    ordered = {k: copy.deepcopy(DEFAULTS[k]) for k in DEFAULT_ORDER}
    # 新增了 DEFAULTS 但忘了 DEFAULT_ORDER 时，至少别丢字段；测试会拦住。
    for k, v in DEFAULTS.items():
        if k not in ordered:
            ordered[k] = copy.deepcopy(v)
    return ordered


